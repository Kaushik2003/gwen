#!/bin/bash
# Builds and updates Gwen Terminal (plan.md 3.14.3): gwen-term, the thin fork of
# Herdr's app in its own checkout, and herdr-core, built from upstream at the
# release pinned in term/core.version. `make term` and `make term-update` run this.
set -euo pipefail

here=$(cd "$(dirname "$0")/.." && pwd)
term_dir=${TERM_DIR:-$HOME/Documents/coding/gwen-term}
core_dir=${CORE_DIR:-${XDG_CACHE_HOME:-$HOME/.cache}/gwen/herdr-core}
core_repo=https://github.com/herdrdev/herdr-core
app_repo=https://github.com/herdrdev/herdr-app
bin=$HOME/.local/bin
# Gwen's own herdr-core lives here, apart from any Herdr you run yourself,
# and runs as the core session "gwen": its own socket, terminals and spaces.
core_bin=$HOME/.local/lib/gwen/herdr-core
generated="gwen: Herdr is called Gwen (generated by scripts/gwen-rename)"
# The Rust version upstream's CI builds with.
export RUSTUP_TOOLCHAIN=${RUST_VERSION:-1.95.0}

die() { echo "term: $*" >&2; exit 1; }

need_tools() {
  command -v cargo >/dev/null || die "Rust isn't installed. See setup.md, Gwen Terminal."
  command -v just >/dev/null || die "just isn't installed. See setup.md, Gwen Terminal."
  command -v zig >/dev/null || die "Zig isn't installed. See setup.md, Gwen Terminal."
  case $(zig version) in 0.16.*) ;; *) die "Zig $(zig version) is installed, but Herdr builds with Zig 0.16. See setup.md, Gwen Terminal." ;; esac
  rustup toolchain list | grep -q "^$RUSTUP_TOOLCHAIN" || rustup toolchain install "$RUSTUP_TOOLCHAIN" --profile minimal
}

need_checkout() {
  [[ -d $term_dir/.git ]] || die "there is no gwen-term checkout at $term_dir. See setup.md, Gwen Terminal."
  [[ $(git -C "$term_dir" branch --show-current) == gwen ]] || die "$term_dir is not on its gwen branch."
  [[ -z $(git -C "$term_dir" status --porcelain) ]] || die "$term_dir has changes that aren't committed. Commit or discard them first."
}

build_core() {
  local tag
  tag=$(tr -d '[:space:]' < "$here/term/core.version")
  if [[ ! -d $core_dir/.git ]]; then
    mkdir -p "$(dirname "$core_dir")"
    git clone --quiet --branch "$tag" --depth 1 "$core_repo" "$core_dir"
  elif [[ $(git -C "$core_dir" describe --tags --exact-match 2>/dev/null) != "$tag" ]]; then
    git -C "$core_dir" fetch --quiet --depth 1 origin "refs/tags/$tag:refs/tags/$tag"
    git -C "$core_dir" checkout --quiet "$tag"
  fi
  git -C "$core_dir" submodule update --quiet --init --depth 1
  echo "term: building herdr-core $tag"
  (cd "$core_dir" && cargo build --locked --release -p herdr-core)
  mkdir -p "$(dirname "$core_bin")"
  install -m 0755 "$core_dir/target/release/herdr-core" "$core_bin.new"
  mv -f "$core_bin.new" "$core_bin"
  # Gwen's core, if it is running, hands its terminals to the new build; they
  # keep running. A Herdr of your own has its own core, which is left alone.
  if HC_SESSION=gwen "$core_bin" server status >/dev/null 2>&1; then
    HC_SESSION=gwen "$core_bin" server restart >/dev/null
  fi
}

# Adds Gwen's entries to the personal programs.json and keeps everything else in it.
merge_programs() {
  local home=${HERDR_APP_HOME:-${XDG_CONFIG_HOME:-$HOME/.config}/gwen-term}
  mkdir -p "$home"
  python3 - "$here/term/programs.json" "$home/programs.json" <<'PY'
import json, os, sys
ours = json.load(open(sys.argv[1]))
path = sys.argv[2]
try:
    theirs = json.load(open(path))
except FileNotFoundError:
    theirs = {}
except ValueError:
    sys.exit(f"term: {path} isn't valid JSON, so Gwen left it alone. Fix it, then run make term again.")
programs = theirs.setdefault("programs", {})
if all(programs.get(k) == v for k, v in ours["programs"].items()):
    sys.exit(0)
programs.update(ours["programs"])
tmp = path + ".new"
with open(tmp, "w") as f:
    json.dump(theirs, f, indent=2)
    f.write("\n")
os.replace(tmp, path)
PY
}

build() {
  need_tools
  need_checkout
  build_core
  echo "term: building gwen-term"
  bash "$term_dir/scripts/install-linux"
  merge_programs
  # The window's own launcher entry stays out of sight: "Gwen" in the launcher is
  # packaging/gwen.desktop, the Gwen window (plan.md 3.15).
  local entry=${XDG_DATA_HOME:-$HOME/.local/share}/applications/gwen-term.desktop
  if [[ -f $entry ]] && ! grep -q '^NoDisplay=true' "$entry"; then
    echo "NoDisplay=true" >> "$entry"
  fi
  # Gwen's themes (and the first W16's mod and key removed); gwend also does this at every start.
  (cd "$here" && go run ./cmd/gwend --install-term) || die "Gwen's themes could not be put in Gwen Terminal's folder."
  echo "term: installed gwen-term $(git -C "$term_dir" describe --tags --always) and its own core, $("$core_bin" --version)."
}

update() {
  need_tools
  need_checkout
  git -C "$term_dir" fetch --quiet upstream
  local base
  base=$(git -C "$term_dir" symbolic-ref --short refs/remotes/upstream/HEAD)
  # The wording commit is generated: drop it, bring the small commits forward, and write it again.
  if [[ $(git -C "$term_dir" log -1 --format=%s) == "$generated" ]]; then
    git -C "$term_dir" reset --quiet --hard HEAD~1
  fi
  if ! git -C "$term_dir" rebase --quiet "$base"; then
    die "Herdr changed something Gwen's patch touches. Resolve it in $term_dir (git status says where), run git rebase --continue, then make term-update again."
  fi
  (cd "$term_dir" && scripts/gwen-rename)
  if [[ -n $(git -C "$term_dir" status --porcelain) ]]; then
    git -C "$term_dir" add -A
    git -C "$term_dir" commit --quiet -m "$generated" -m "Regenerate after a rebase: drop this commit, rebase the rest, run
scripts/gwen-rename and commit again."
  fi
  echo "term: running Herdr's checks"
  (cd "$term_dir" && PATH="$(dirname "$core_bin"):$PATH" just check) || die "Herdr's checks fail on the gwen branch. Nothing was installed."
  local newest pinned
  newest=$(git ls-remote --tags --refs "$core_repo" 'v*' | sed 's|.*refs/tags/||' | sort -V | tail -1)
  pinned=$(tr -d '[:space:]' < "$here/term/core.version")
  echo "term: gwen-term is now at $(git -C "$term_dir" describe --tags --always). Run make term to build and install it."
  [[ $newest == "$pinned" ]] || echo "term: herdr-core $newest is out; term/core.version pins $pinned. Change it to move."
}

# Builds Gwen Terminal and its core only when one is missing or the core isn't the pinned release, so
# `make install-dev` can run it every time without rebuilding Herdr or restarting Gwen's core for nothing.
ensure() {
  local tag have=""
  tag=$(tr -d '[:space:]' < "$here/term/core.version")
  [[ -x $core_bin ]] && have=$("$core_bin" --version 2>/dev/null | awk '{print $2}')
  if [[ v$have == "$tag" && -x $bin/gwen-term ]]; then
    echo "term: Gwen Terminal and herdr-core $tag are installed."
    return
  fi
  build
}

case ${1:-} in
  build) build ;;
  ensure) ensure ;;
  update) update ;;
  *) die "usage: scripts/term.sh build|ensure|update ($app_repo, $core_repo)" ;;
esac
